#!/usr/bin/env node
/**
 * Writes two review documents from committed files (Stage 8 deliverables):
 * - docs/data-source-inventory.md: every source in the published data index (verified status,
 *   publisher, licence, link) and the datasets built from it, with snapshot and reference period;
 * - docs/consulting-services.md: the nine services and About text from src/content/consulting.json,
 *   for ConsultingWhere's review (decision D7).
 * Rerun after a data refresh or a content change:  node scripts/docs-inventory.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
const cell = (s) =>
  String(s ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\s+/g, " ")
    .trim();

const m = read("public/data/manifest.json");
const used = new Map();
for (const d of m.datasets) for (const s of d.sourceIds) used.set(s, [...(used.get(s) ?? []), d]);
const lines = [
  "# Verified data-source inventory",
  "",
  `Generated by \`scripts/docs-inventory.mjs\` from the published data index (\`public/data/manifest.json\`, generated ${m.generatedAt ?? "—"}). Every source below is marked verified in the data index; the verification log, field names and caveats are in \`docs/03-DATA-SOURCES.md\`. Sources listed there but not used by a published dataset (planned or context-only) are not repeated here.`,
  "",
  "| ID | Source | Publisher | Licence | Status | Datasets built from it (snapshot · reference period) |",
  "|---|---|---|---|---|---|",
];
const num = (id) => Number(id.slice(1));
for (const c of [...m.catalogue].sort((a, b) => num(a.id) - num(b.id))) {
  const ds = (used.get(c.id) ?? [])
    .map(
      (d) =>
        `${d.title} (${/snapshots\/(\d{4}-\d{2}-\d{2})\//.exec(d.path)?.[1] ?? "—"} · ${d.referencePeriod})`,
    )
    .join("; ");
  lines.push(
    `| ${c.id} | ${c.url ? `[${cell(c.title)}](${c.url})` : cell(c.title)} | ${cell(c.publisher)} | ${cell(c.licence)} | ${cell(c.status)} | ${cell(ds) || "—"} |`,
  );
}
lines.push(
  "",
  "## Datasets",
  "",
  "| Dataset | Snapshot | Provenance | Licence | Attribution | SHA-256 |",
  "|---|---|---|---|---|---|",
);
for (const d of m.datasets)
  lines.push(
    `| ${cell(d.title)} (\`${d.id}\`) | ${/snapshots\/(\d{4}-\d{2}-\d{2})\//.exec(d.path)?.[1] ?? "—"} | ${d.provenance} | ${cell(d.licence)} | ${cell(d.attribution)} | \`${d.sha256.slice(0, 12)}\` |`,
  );
writeFileSync(join(root, "docs/data-source-inventory.md"), `${lines.join("\n")}\n`);

const content = read("src/content/consulting.json");
const out = [
  "# ConsultingWhere services and About text (for approval)",
  "",
  `Generated by \`scripts/docs-inventory.mjs\` from \`src/content/consulting.json\`. Approval status: **${content.status.approval}**. ${content.status.note}`,
  "",
  `## ${content.about.title}`,
  "",
  ...content.about.paragraphs.flatMap((p) => [p, ""]),
  "Principles:",
  "",
  ...content.about.principles.map((p) => `- ${p}`),
  "",
];
content.services.forEach((s, i) => {
  out.push(`## ${i + 1}. ${s.title}`, "", `*${s.strapline}*`, "");
  for (const [h, items] of [
    ["Challenges", s.challenges],
    ["Approach", s.approach],
    ["Deliverables", s.deliverables],
    ["Value", s.value],
    ["Stakeholders", s.stakeholders],
  ])
    out.push(`**${h}**`, "", ...items.map((x) => `- ${x}`), "");
});
writeFileSync(join(root, "docs/consulting-services.md"), `${out.join("\n").trimEnd()}\n`);
console.log("docs-inventory: wrote docs/data-source-inventory.md and docs/consulting-services.md");
