#!/usr/bin/env node
/**
 * Writes public/licenses/THIRD-PARTY-NOTICES.txt: the licence of every production dependency the
 * built app redistributes (npm ls --omit=dev), with its copyright and licence text from the
 * package, as MIT, BSD, Apache, ISC and the SIL Open Font License require for copies (the
 * minified bundle keeps no licence comments). Rerun after changing dependencies; a unit test checks
 * the file lists every production dependency.
 *
 *   node scripts/third-party-notices.mjs
 */
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// Parseable output lists each installed package once with its path: "<path>:<name>@<version>[:...]".
const listing = execSync("npm ls --omit=dev --all --parseable --long", {
  cwd: root,
  maxBuffer: 1e9,
}).toString();
const packages = new Map();
for (const line of listing.split("\n")) {
  const [path, spec] = line.split(":");
  if (!path || !spec || path === root) continue;
  const at = spec.lastIndexOf("@");
  const name = spec.slice(0, at);
  const version = spec.slice(at + 1);
  if (name && version && !packages.has(`${name}@${version}`))
    packages.set(`${name}@${version}`, { name, version, path });
}

function licenceText(dir) {
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  return file ? readFileSync(join(dir, file), "utf8").trim() : null;
}

const lines = [
  "FOODSCOPE UK: third-party notices",
  "",
  "The application redistributes the following packages in its built files. Each is listed with its",
  "licence as declared by the package and the licence text it ships with.",
  "Generated by scripts/third-party-notices.mjs from the production dependency tree.",
  "",
];
const sorted = [...packages.values()].sort(
  (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
);
for (const p of sorted) {
  const pkg = JSON.parse(readFileSync(join(p.path, "package.json"), "utf8"));
  const licence =
    typeof pkg.license === "string"
      ? pkg.license
      : JSON.stringify(pkg.license ?? pkg.licenses ?? "not declared");
  lines.push(
    "=".repeat(100),
    `${p.name} ${p.version}`,
    `Licence: ${licence}`,
    pkg.homepage ? `Homepage: ${pkg.homepage}` : "",
    "",
  );
  const text = licenceText(p.path);
  lines.push(text ?? "(No licence file in the package; see the declared licence above.)", "");
}
const out = join(root, "public", "licenses");
if (!existsSync(out)) mkdirSync(out, { recursive: true });
writeFileSync(
  join(out, "THIRD-PARTY-NOTICES.txt"),
  `${lines.filter((l, i, a) => !(l === "" && a[i - 1] === "")).join("\n")}\n`,
);
console.log(`third-party-notices: ${sorted.length} packages`);
